"""Generate the Rust gallery data from the reviewed photo manifest."""
import argparse
import json
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
root = Path(__file__).resolve().parent.parent
photos = json.loads((root / "docs/PROGRAM-PHOTOS.json").read_text(encoding="utf-8"))
lines = ["// Generated by scripts/generate-photo-data.py from docs/PROGRAM-PHOTOS.json.", ""]
for program in ("geography", "anatomy", "art"):
    lines.append(f"const {program.upper()}: &[Photo] = &[")
    for photo in (p for p in photos if p["program"] == program):
        lines.append("    Photo {")
        for field in ("file", "title", "caption", "alt"):
            lines.append(f"        {field}: {json.dumps(photo[field], ensure_ascii=False)},")
        lines.extend([f'        width: {photo["size"][0]},', f'        height: {photo["size"][1]},', "    },"])
    lines.extend(["];", ""])
generated = "\n".join(lines)
output = root / "src/gallery_photos.rs"
if args.check:
    assert output.read_text(encoding="utf-8") == generated, "Run python scripts/generate-photo-data.py"
    print(f"Gallery source matches all {len(photos)} approved images.")
else:
    output.write_text(generated, encoding="utf-8")
    print(f"Generated {len(photos)} gallery entries.")
